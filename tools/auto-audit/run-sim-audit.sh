#!/usr/bin/env bash
# Run the headless hood-vs-trench simulation audit, one fresh JVM per auto.
#
#   tools/auto-audit/run-sim-audit.sh [options] [name ...]
#
#   --alliance Blue|Red            default Blue
#   --seconds N                    simulated seconds per auto (default 20 = the AUTO period)
#   --update-baseline              record each auto's verdict in src/test/resources/auto-audit/baseline.json
#   --strict                       also fail when a baseline entry no longer reproduces
#   --repeat N                     run each auto N times (PathPlanner results vary run to run)
#   name ...                       PathPlanner auto names (default: all autos)
#
# Exit status is non-zero if any auto has a hood-up-in-trench violation that is not in the baseline.
set -u
cd "$(dirname "$0")/../.."

alliance=Blue; seconds=20; update=0; strict=0; repeat=1; names=()
while [ $# -gt 0 ]; do
  case "$1" in
    --alliance) alliance=$2; shift 2 ;;
    --seconds) seconds=$2; shift 2 ;;
    --update-baseline) update=1; shift ;;
    --strict) strict=1; shift ;;
    --repeat) repeat=$2; shift 2 ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) names+=("$1"); shift ;;
  esac
done

# (kind|chooser label|file) triples
jobs=()
add_pp_all() {
  for f in src/main/deploy/pathplanner/autos/*.auto; do n=$(basename "$f" .auto); echo "pathplanner|$n|$n"; done
}
if [ ${#names[@]} -eq 0 ]; then
  while IFS= read -r l; do jobs+=("$l"); done < <(add_pp_all)
else
  for n in "${names[@]}"; do
    if [ -f "src/main/deploy/pathplanner/autos/$n.auto" ]; then jobs+=("pathplanner|$n|$n")
    else echo "unknown auto '$n'"; exit 2; fi
  done
fi

# BuildConstants.java is regenerated by every build; put it back afterwards if it was clean.
restore_bc=0; git diff --quiet -- src/main/java/frc/robot/BuildConstants.java && restore_bc=1

fail=0; i=0
for j in "${jobs[@]}"; do
 for rep in $(seq 1 "$repeat"); do
  IFS='|' read -r k label file <<<"$j"; i=$((i+1))
  log=$(mktemp)
  AUDIT_KIND=$k AUDIT_AUTO=$label AUDIT_FILE=$file AUDIT_ALLIANCE=$alliance AUDIT_SECONDS=$seconds \
  AUDIT_UPDATE_BASELINE=$update AUDIT_STRICT_BASELINE=$strict \
  ./gradlew cleanTest test --tests 'frc.robot.rebuilt.audit.AutoAuditSimTest' \
      -x spotlessApply -x spotlessJava --console=plain -i >"$log" 2>&1
  rc=$?
  line=$(grep -h '\[auto-audit\]' "$log" | sed 's/^ *//' | head -3)
  if [ $rc -ne 0 ]; then fail=$((fail+1)); echo "[$i/$((${#jobs[@]} * repeat))] FAIL $k '$file'"; echo "$line"; grep -h -A3 'NEW sim violation\|AssertionFailedError\|robot thread died' "$log" | head -6
  else echo "[$i/$((${#jobs[@]} * repeat))] ok   $k '$file'"; echo "$line" | sed 's/^/    /'; fi
  rm -f "$log"
 done
done
[ $restore_bc -eq 1 ] && git checkout -- src/main/java/frc/robot/BuildConstants.java 2>/dev/null
echo "done: $((${#jobs[@]} * repeat)) run, $fail failing"
[ $fail -eq 0 ]
